function deskpetDrawSprite(ctx, species, frame, x, y, scale, flip) {
  const spec = DESKPET_SPRITES[species];
  const rows = spec.frames[frame] || spec.frames.idle;
  ctx.save();
  ctx.imageSmoothingEnabled = false;
  ctx.translate(x, y);
  if (flip) {
    ctx.translate(spec.w * scale, 0);
    ctx.scale(-1, 1);
  }
  for (let row = 0; row < rows.length; row++) {
    const line = rows[row];
    for (let col = 0; col < line.length; col++) {
      const key = line[col];
      if (key === "0") continue;
      ctx.fillStyle = spec.palette[Number(key)];
      ctx.fillRect(col * scale, row * scale, scale, scale);
    }
  }
  ctx.restore();
}
